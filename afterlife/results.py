"""Render RESULTS.md from run reports. No number in it is typed by hand.

    afterlife results --findings runs/<timestamp>-findings.json

Every table names the report and key it came from. Rerunning the pipeline and
this command regenerates the file; editing RESULTS.md directly is pointless.
"""

from __future__ import annotations

import json
from pathlib import Path

from afterlife.gold import ROOT

NAMES = {
    "retraction_watch": "Retraction Watch",
    "openalex": "OpenAlex",
    "pubmed": "PubMed",
    "pmc": "PMC",
}
ELIGIBLE = {
    "retraction_watch": "every paper",
    "openalex": "papers with a DOI or PMID",
    "pubmed": "papers with a PMID",
    "pmc": "papers with a linked PMC open copy",
}


def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def _n(x) -> str:
    if x is None:
        return ""
    if isinstance(x, float) and not x.is_integer():
        return f"{x:,.1f}"
    return f"{int(x):,}"


def _table(header: list[str], rows: list[list]) -> str:
    out = [
        "| " + " | ".join(str(h) for h in header) + " |",
        "| " + " | ".join("---" for _ in header) + " |",
    ]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _latest(pattern: str) -> Path | None:
    found = sorted((ROOT / "runs").glob(pattern))
    return found[-1] if found else None


def render(findings_path: Path) -> str:
    rep = json.loads(findings_path.read_text())["report"]
    src = f"`{findings_path.relative_to(ROOT)}`"
    s, g, lag, aft, rs, up = (
        rep[k]
        for k in ("sources", "registries", "retraction_lag", "afterlife", "reasons", "upstream")
    )
    parts = [
        "# Results",
        "",
        "Generated by `afterlife results` from run reports. Every number below "
        f"comes from {src} unless a section names another report. All runs used real "
        "public data fetched on 2026-10-19.",
    ]

    rw = s["retraction_watch"]
    oa, pm, pmc = s["openalex"], s["pubmed"], s["pmc_metadata"]
    parts += [
        "",
        "## 1. What was landed",
        "",
        _table(
            ["Source", "Landed", "Detail", "Cost"],
            [
                [
                    "Retraction Watch",
                    f"{rw['snapshots']} snapshots, {rw['first']} to {rw['last']}",
                    f"{_n(rw['records_first'])} records growing to {_n(rw['records_last'])}",
                    "$0",
                ],
                [
                    "OpenAlex",
                    f"{_n(oa['records'])} of {_n(oa['expected'])} retracted works",
                    f"{_n(oa['calls'])} calls, keyless date partitioned paging, "
                    f"{_n(oa['uncovered_by_date_slices'])} works outside the date slices",
                    f"${oa['spent_usd']:.4f}",
                ],
                [
                    "PubMed",
                    f"{_n(pm['records'])} PMIDs",
                    f"year slices sum to {_n(pm['slice_count_sum'])}; "
                    f"{_n(pm['records_in_more_than_one_slice'])} records match two slices",
                    "$0",
                ],
                [
                    "PMC",
                    f"{_n(pmc['requested'])} metadata objects requested",
                    f"{_n(pmc['in_open_data'])} in the open data subset, "
                    f"{_n(pmc['flagged_retracted'])} flagged is_retracted",
                    "$0",
                ],
            ],
        ),
    ]
    bad = rw["non_utf8_snapshots"]
    if bad:
        parts += [
            "",
            "Snapshots not in UTF-8: "
            + "; ".join(
                f"{b['snapshot_date']} ({b['encoding']}, {_n(b['invalid_utf8_bytes'])} invalid "
                "UTF-8 bytes)"
                for b in bad
            )
            + ". Key `sources.retraction_watch`.",
        ]

    parts += [
        "",
        "## 2. Registry agreement",
        "",
        f"Papers flagged retracted (or disputed) by at least one registry: "
        f"{_n(g['papers'])}. All eligible registries agree on {_n(g['all_eligible_agree'])} "
        f"({_pct(g['all_eligible_agree'], g['papers'])}); exactly one registry flags "
        f"{_n(g['flagged_by_exactly_one'])} ({_pct(g['flagged_by_exactly_one'], g['papers'])})."
        " Key `registries`.",
        "",
        _table(
            ["Registry", "Eligible means", "Eligible", "Flagged", "Recall against union"],
            [
                [
                    NAMES[a["source"]],
                    ELIGIBLE[a["source"]],
                    _n(a["eligible"]),
                    _n(a["flagged"]),
                    _pct(a["flagged"], a["eligible"]),
                ]
                for a in sorted(g["agreement"], key=lambda a: -a["flagged"] / a["eligible"])
            ],
        ),
        "",
        "Verdicts: " + ", ".join(f"{k} {_n(v)}" for k, v in g["by_verdict"].items()) + ".",
        "",
        "Most common flag combinations (null: the source has no linked record):",
        "",
        _table(
            ["Retraction Watch", "OpenAlex", "PubMed", "PMC", "Papers"],
            [
                [c["rw"], c["openalex"], c["pubmed"], c["pmc"], _n(c["papers"])]
                for c in g["combinations"]
            ],
        ),
    ]

    excluded = g["excluded_as_notices"]
    oa_notices = sum(e["rows_excluded"] for e in excluded if e["source"] == "openalex")
    pn = g["pmc_notice_articles"]
    parts += [
        "",
        "## 3. Notices excluded from the registry",
        "",
        f"OpenAlex rows excluded as notices: {_n(oa_notices)} of {_n(oa['records'])} "
        f"({_pct(oa_notices, oa['records'])}). PMC holds {_n(pn['notice_articles'])} notice "
        f"articles, of which {_n(pn['flagged_is_retracted'])} carry is_retracted. "
        "Key `registries.excluded_as_notices`.",
        "",
        _table(
            ["Source", "Reason", "Rows excluded"],
            [
                [
                    NAMES.get(e["source"], e["source"]),
                    f"`{e['notice_reason']}`",
                    _n(e["rows_excluded"]),
                ]
                for e in excluded
            ],
        ),
    ]

    parts += [
        "",
        "## 4. Time to retraction",
        "",
        f"{_n(lag['notices'])} dated retraction notices; median {_n(lag['median_days'])} days, "
        f"interquartile range {_n(lag['p25_days'])} to {_n(lag['p75_days'])}; "
        f"{_n(lag['negative_lag_excluded'])} notice dated before its paper excluded. "
        "Key `retraction_lag`.",
        "",
        _table(
            ["Notice year", "Notices", "Median days"],
            [
                [y["retraction_year"], _n(y["notices"]), _n(y["median_days"])]
                for y in lag["by_retraction_year"]
            ],
        ),
    ]

    h, rr = aft["headline_excluding_retract_and_replace"], aft["retract_and_replace_only"]
    parts += [
        "",
        "## 5. Citations after retraction",
        "",
        f"{_n(aft['papers'])} retracted papers matched in OpenAlex with a retraction date; "
        f"{_n(aft['window_complete'])} have their whole post retraction period inside "
        "OpenAlex's citation window (counts_by_year starts in 2012). Citations count as "
        "after retraction only in years strictly after the retraction year. "
        "Key `afterlife`.",
        "",
        _table(
            [
                "Group",
                "Papers",
                "Cited after retraction",
                "Citations after",
                "Median after",
                "90th percentile after",
            ],
            [
                [
                    "Headline (excluding retract and replace)",
                    _n(h["papers"]),
                    f"{_n(h['with_any_after'])} ({_pct(h['with_any_after'], h['papers'])})",
                    _n(h["citations_after"]),
                    _n(h["median_after"]),
                    _n(h["p90_after"]),
                ],
                [
                    "Retract and replace only",
                    _n(rr["papers"]),
                    f"{_n(rr['with_any_after'])} ({_pct(rr['with_any_after'], rr['papers'])})",
                    _n(rr["citations_after"]),
                    _n(rr["median_after"]),
                    _n(rr["p90_after"]),
                ],
            ],
        ),
        "",
        "Most cited after retraction (headline group):",
        "",
        _table(
            [
                "DOI or key",
                "Title",
                "Retracted",
                "Citations after",
                "Citations through retraction year",
            ],
            [
                [
                    t["paper_key"].removeprefix("doi:"),
                    (t["title"] or "")[:80],
                    t["retraction_year"],
                    _n(t["citations_after"]),
                    _n(t["citations_through_retraction_year"]),
                ]
                for t in aft["top_by_citations_after"]
            ],
        ),
    ]

    series: dict[str, dict[int, int]] = {}
    for x in rs["series"]:
        series.setdefault(x["reason"], {})[x["retraction_year"]] = x["notices"]
    years = list(range(2018, rs["last_complete_year"] + 2))
    parts += [
        "",
        "## 6. Reasons",
        "",
        f"Top reasons in {rs['last_complete_year']}, the last complete year. Key `reasons`.",
        "",
        _table(
            ["Reason", "Notices"],
            [[x["reason"], _n(x["notices"])] for x in rs["top_last_complete_year"]],
        ),
        "",
        "Selected reasons by notice year (the final year is partial):",
        "",
        _table(
            ["Reason", *years], [[k, *(_n(v.get(y, 0)) for y in years)] for k, v in series.items()]
        ),
    ]

    e = up["records_edited_after_first_appearance"]
    parts += [
        "",
        "## 7. What the source changed",
        "",
        f"From the silver replay `runs/{up['replay_report']}` over {up['snapshots']} snapshots. "
        "Key `upstream`.",
        "",
        _table(
            ["Measure", "Value"],
            [
                ["Records ever seen", _n(e["records_ever_seen"])],
                [
                    "Records edited after first appearance",
                    f"{_n(e['records_ever_updated'])} "
                    f"({_pct(e['records_ever_updated'], e['records_ever_seen'])})",
                ],
                [
                    "Edited in something other than reasons",
                    f"{_n(e['records_updated_beyond_reason'])} "
                    f"({_pct(e['records_updated_beyond_reason'], e['records_ever_seen'])})",
                ],
                ["Original DOI changed", _n(e["records_doi_changed"])],
                ["Retraction date changed", _n(e["records_retraction_date_changed"])],
                [
                    "Nature changed (for example concern to retraction)",
                    _n(e["records_nature_changed"]),
                ],
                ["Semantic updates, all snapshots", _n(up["semantic_updates_total"])],
                ["Format only changes, all snapshots", _n(up["format_only_total"])],
                ["Deleted, reappeared", f"{_n(up['deleted_total'])}, {_n(up['reappeared_total'])}"],
                ["Blank rows dropped", _n(up["blank_rows_dropped"])],
            ],
        ),
        "",
        "Quarantined snapshots:",
        "",
        _table(
            ["Snapshot", "Records with the lossy signature", "By column"],
            [
                [
                    q["snapshot_date"],
                    _n(q["lossy_records"]),
                    ", ".join(f"{k} {_n(v)}" for k, v in q["lossy_by_column"].items()),
                ]
                for q in up["quarantined"]
            ],
        ),
        "",
        "Largest relabels of the reason taxonomy (case insensitive):",
        "",
        _table(
            ["Date", "Removed", "Added", "Records"],
            [
                [x["change_date"], "; ".join(x["removed"]), "; ".join(x["added"]), _n(x["records"])]
                for x in up["top_reason_relabels"]
            ],
        ),
    ]

    conf = _latest("*-conformance.json")
    if conf:
        c = json.loads(conf.read_text())["report"]
        parts += [
            "",
            "## 8. Cross engine conformance",
            "",
            f"From `runs/{conf.name}`: the gold models built on DuckDB and on Spark SQL, every "
            "row compared after normalizing decimals to 6 places and dates to ISO strings.",
            "",
            _table(
                ["Mart", "Rows", "Identical"],
                [
                    [m, _n(v["rows_duckdb"]), "yes" if v["identical"] else "NO"]
                    for m, v in c["marts"].items()
                ],
            ),
        ]
    golds = sorted((ROOT / "runs").glob("*-gold.json"))
    by_target: dict[str, dict] = {}
    for p in golds:
        r = json.loads(p.read_text())["report"]
        if r.get("exit_code") == 0:
            by_target[r["target"]] = {"file": p.name, **r}
    if by_target:
        parts += [
            "",
            "## 9. dbt builds",
            "",
            _table(
                ["Target", "Report", "Models and tests", "Seconds"],
                [
                    [
                        t,
                        f"`runs/{r['file']}`",
                        ", ".join(f"{k} {v}" for k, v in r["status_counts"].items()),
                        r["elapsed_s"],
                    ]
                    for t, r in sorted(by_target.items())
                ],
            ),
        ]
    return "\n".join(parts) + "\n"


def run(findings: str | None = None, out: str = "RESULTS.md") -> dict:
    path = Path(findings) if findings else _latest("*-findings.json")
    if path is None:
        raise SystemExit("no findings report under runs/; run `afterlife findings` first")
    path = path.resolve()
    text = render(path)
    (ROOT / out).write_text(text)
    return {"findings": str(path.relative_to(ROOT)), "wrote": out, "lines": text.count("\n")}
